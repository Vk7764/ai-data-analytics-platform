export function getLanguage() {
  return localStorage.getItem("app_language") === "hi" ? "hi" : "en";
}

export function setLanguage(lang) {
  localStorage.setItem("app_language", lang === "hi" ? "hi" : "en");
  window.dispatchEvent(new Event("app-language-changed"));
}

export function useLanguage() {
  const [lang, setLangState] = useState(getLanguage());
  useEffect(() => {
    const onChange = () => setLangState(getLanguage());
    window.addEventListener("app-language-changed", onChange);
    return () => window.removeEventListener("app-language-changed", onChange);
  }, []);
  return {
    lang,
    t: (key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key,
    setLanguage,
  };
}